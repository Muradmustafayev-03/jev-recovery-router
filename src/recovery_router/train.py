"""Single-device, bounded LoRA adaptation with resumable optimizer checkpoints."""
from __future__ import annotations

import argparse
import hashlib
import json
import math
from pathlib import Path
import random
import time

import torch

from .model import (InputTooLong, collate_views, create_model, encode_view,
                    load_model_bundle, make_view, save_model_bundle)


def seed_all(seed: int):
    random.seed(seed)
    torch.manual_seed(seed)
    if torch.cuda.is_available():
        torch.cuda.manual_seed_all(seed)


def prepare_views(data_path, tokenizer, max_length, seed=42, shuffle_candidates=True):
    rng = random.Random(seed)
    views, rejected = [], []
    for line in Path(data_path).read_text(encoding="utf-8").splitlines():
        if not line.strip():
            continue
        record = json.loads(line)
        if record.get("intervention") not in (None, "", "none", "natural"):
            rejected.append({"id": record["id"], "reason": "non-natural training record"})
            continue
        if "label" not in record:
            raise ValueError(f"Missing training label: {record.get('id')}")
        for expanded in (False, True):
            view = make_view(record, expanded, rng if shuffle_candidates else None)
            try:
                views.append(encode_view(tokenizer, view, max_length))
            except InputTooLong as exc:
                rejected.append({"id": record["id"], "stage": view["stage"], "reason": str(exc)})
    if not views:
        raise ValueError("No usable training views remain; inspect input length or intervention filtering")
    return views, rejected


def main(argv=None):
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--config", required=True)
    parser.add_argument("--data", required=True)
    parser.add_argument("--output", required=True)
    parser.add_argument("--smoke-steps", type=int, default=0,
                        help="Stop after this many optimizer updates; 50 is a useful throughput smoke test")
    parser.add_argument("--max-seconds", type=float)
    parser.add_argument("--resume", help="Local trusted checkpoint bundle containing training_state.pt")
    parser.add_argument("--device", default="cuda", choices=("cpu", "cuda"))
    args = parser.parse_args(argv)
    started = time.monotonic()
    config = json.loads(Path(args.config).read_text(encoding="utf-8"))
    model_cfg = dict(config.get("model", {}))
    train_cfg = config.get("training", config.get("train", {}))
    seed = int(train_cfg.get("seed", config.get("seed", 42)))
    seed_all(seed)
    if args.device == "cuda" and not torch.cuda.is_available():
        raise RuntimeError("CUDA was requested but is unavailable; use --device cpu only for small smoke tests")
    max_length = int(model_cfg.get("max_length", 512))
    max_seconds = args.max_seconds if args.max_seconds is not None else float(train_cfg.get("max_seconds", 7200))
    if max_seconds <= 0:
        raise ValueError("max_seconds must be positive")
    output = Path(args.output)
    output.mkdir(parents=True, exist_ok=True)
    trained_counts = set()
    if args.resume:
        model, tokenizer, saved_meta = load_model_bundle(args.resume, args.device, trainable=True)
        if saved_meta["model"] != model_cfg:
            raise ValueError("Resume model configuration differs from the saved bundle")
        trained_counts.update(saved_meta.get("trained_candidate_counts", []))
    else:
        model, tokenizer = create_model(model_cfg, args.device)
    views, rejected = prepare_views(args.data, tokenizer, max_length, seed,
                                    bool(train_cfg.get("shuffle_candidates", True)))
    (output / "rejected_training_views.jsonl").write_text(
        "".join(json.dumps(r) + "\n" for r in rejected), encoding="utf-8")
    data_sha = hashlib.sha256(Path(args.data).read_bytes()).hexdigest()
    view_sha = hashlib.sha256(json.dumps([
        [v["id"], v["stage"], v["input_ids"], v["target"]] for v in views
    ], separators=(",", ":")).encode()).hexdigest()
    batch_size = int(train_cfg.get("micro_batch_size", train_cfg.get("batch_size", 8)))
    accumulation = int(train_cfg.get("gradient_accumulation_steps", 4))
    epochs = int(train_cfg.get("epochs", 1))
    if min(batch_size, accumulation, epochs) < 1:
        raise ValueError("Batch size, accumulation and epochs must be positive")
    optimizer = torch.optim.AdamW([p for p in model.parameters() if p.requires_grad],
                                  lr=float(train_cfg.get("learning_rate", 2e-4)),
                                  weight_decay=float(train_cfg.get("weight_decay", .01)))
    global_step, first_epoch, first_batch = 0, 0, 0
    if args.resume:
        # This file is generated by our own local run, never load an untrusted checkpoint.
        state = torch.load(Path(args.resume) / "training_state.pt", map_location="cpu", weights_only=False)
        if state["data_sha256"] != data_sha or state["views_sha256"] != view_sha:
            raise ValueError("Training data/views changed; refusing an inconsistent resume")
        if state["training_config"] != train_cfg:
            raise ValueError("Training configuration changed; refusing an inconsistent resume")
        if state.get("trained_candidate_counts", []) != sorted(trained_counts):
            raise ValueError("Trained candidate-count history differs between metadata and optimizer checkpoint")
        optimizer.load_state_dict(state["optimizer"])
        for optim_state in optimizer.state.values():
            for key, value in optim_state.items():
                if isinstance(value, torch.Tensor):
                    optim_state[key] = value.to(args.device)
        global_step, first_epoch, first_batch = state["step"], state["next_epoch"], state["next_batch"]
        torch.set_rng_state(state["torch_rng"])
        random.setstate(state["python_rng"])
        if args.device == "cuda" and state.get("cuda_rng"):
            torch.cuda.set_rng_state_all(state["cuda_rng"])
    total_batches = math.ceil(len(views) / batch_size)
    planned_steps = epochs * math.ceil(total_batches / accumulation)
    print(json.dumps({"event": "prepared", "views": len(views), "rejected": len(rejected),
                      "planned_optimizer_steps": planned_steps,
                      "trainable_parameters": sum(p.numel() for p in model.parameters() if p.requires_grad)}), flush=True)
    step_times, losses = [], []
    next_epoch, next_batch = first_epoch, first_batch
    checkpoint_steps = int(train_cfg.get("checkpoint_steps", 100))
    stop_reason = "epochs_complete"
    initial_step = global_step
    model.train()

    def checkpoint(destination):
        save_model_bundle(model, tokenizer, destination, model_cfg,
                          {"step": global_step, "data_sha256": data_sha, "training_data_sha256": data_sha,
                           "views_sha256": view_sha,
                           "training_config_sha256": hashlib.sha256(Path(args.config).read_bytes()).hexdigest(),
                           "trained_candidate_counts": sorted(trained_counts),
                           "planned_candidate_counts": sorted({v["candidate_count"] for v in views}),
                           "max_length": max_length})
        torch.save({"optimizer": optimizer.state_dict(), "step": global_step,
                    "next_epoch": next_epoch, "next_batch": next_batch,
                    "trained_candidate_counts": sorted(trained_counts),
                    "data_sha256": data_sha, "views_sha256": view_sha, "training_config": train_cfg,
                    "torch_rng": torch.get_rng_state(), "python_rng": random.getstate(),
                    "cuda_rng": torch.cuda.get_rng_state_all() if args.device == "cuda" else None},
                   Path(destination) / "training_state.pt")

    for epoch in range(first_epoch, epochs):
        order = list(range(len(views)))
        random.Random(seed + 1000 + epoch).shuffle(order)
        batch_start = first_batch if epoch == first_epoch else 0
        for group_start in range(batch_start, total_batches, accumulation):
            if time.monotonic() - started >= max_seconds:
                stop_reason = "time_cap"
                break
            tick = time.monotonic()
            optimizer.zero_grad(set_to_none=True)
            group_stop = min(total_batches, group_start + accumulation)
            selected = [order[b * batch_size:(b + 1) * batch_size] for b in range(group_start, group_stop)]
            group_examples = sum(map(len, selected))
            step_loss = 0.
            for indices in selected:
                batch = collate_views(tokenizer, [views[i] for i in indices], max_length)
                batch = {k: v.to(args.device) for k, v in batch.items()}
                result = model(**batch)
                weighted_loss = result["loss"] * (len(indices) / group_examples)
                if not torch.isfinite(weighted_loss):
                    raise FloatingPointError(f"Non-finite loss at optimizer step {global_step + 1}")
                weighted_loss.backward()
                step_loss += float(weighted_loss.detach())
            torch.nn.utils.clip_grad_norm_([p for p in model.parameters() if p.requires_grad],
                                          float(train_cfg.get("max_grad_norm", 1.)),
                                          error_if_nonfinite=True)
            optimizer.step()
            trained_counts.update(views[i]["candidate_count"] for indices in selected for i in indices)
            if args.device == "cuda":
                torch.cuda.synchronize()
            global_step += 1
            next_epoch = epoch + 1 if group_stop == total_batches else epoch
            next_batch = 0 if group_stop == total_batches else group_stop
            step_times.append(time.monotonic() - tick)
            losses.append(step_loss)
            if global_step % 10 == 0 or global_step == initial_step + 1:
                print(json.dumps({"event": "step", "step": global_step, "loss": step_loss,
                                  "seconds_per_step": sum(step_times[-20:]) / len(step_times[-20:]),
                                  "elapsed_seconds": time.monotonic() - started}), flush=True)
            if checkpoint_steps and global_step % checkpoint_steps == 0:
                checkpoint(output / "checkpoints" / f"step-{global_step:06d}")
            if args.smoke_steps and global_step - initial_step >= args.smoke_steps:
                stop_reason = "smoke_steps"
                break
        if stop_reason != "epochs_complete":
            break
    checkpoint(output)
    steady_times = step_times[5:] or step_times
    mean_step = sum(steady_times) / len(steady_times) if steady_times else None
    report = {"stop_reason": stop_reason, "optimizer_steps_this_run": global_step - initial_step,
              "optimizer_steps_total": global_step, "planned_optimizer_steps": planned_steps,
              "usable_views": len(views), "rejected_views": len(rejected),
              "mean_step_seconds_excluding_first_five": mean_step,
              "estimated_remaining_training_seconds": max(0, planned_steps - global_step) * mean_step if mean_step else None,
              "elapsed_seconds": time.monotonic() - started,
              "last_loss": losses[-1] if losses else None,
              "note": "Time cap is checked between optimizer updates; setup/checkpoint saving can overrun it."}
    (output / "training_report.json").write_text(json.dumps(report, indent=2), encoding="utf-8")
    print(json.dumps(report), flush=True)
    if global_step == 0:
        raise SystemExit("No optimizer update completed. Saved diagnostic bundle is untrained; do not evaluate it as an adapted model.")


if __name__ == "__main__":
    main()
